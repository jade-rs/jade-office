#!/usr/bin/env python3
"""Index unmodified, hash-pinned normative ECMA pivot style definitions."""
from pathlib import Path
import hashlib,re,subprocess
root=Path(__file__).resolve().parents[2]
p=root/'jade-core/crates/jade-xlsx-layout/data/presetTableStyles.xml'
s=p.read_bytes()
assert hashlib.sha256(s).hexdigest()=='74c6cf73d551bb2bd33a51690d4922095260b6647b2a38fcbc0d6da6c6275d7e'
entries=[(m[1].decode(),m.start(2),m.end(2)) for m in re.finditer(rb'<(PivotStyle(?:Light|Medium|Dark)\d+)>(.*?)</\1>',s,re.S)]
assert len(entries)==84
out=root/'jade-core/crates/jade-xlsx-layout/src/pivot_style/preset_offsets.rs'
out.write_text('// Byte spans in the unmodified ECMA-376 data; regenerated by scripts/xlsx/generate_pivot_style_offsets.py.\npub(super) const OFFSETS: &[(&str,usize,usize)] = &[\n'+''.join(f'    ("{n}",{a},{z}),\n' for n,a,z in entries)+'];\n')
subprocess.run(["rustfmt","--edition","2021","--config","skip_children=true",str(out)],check=True)
